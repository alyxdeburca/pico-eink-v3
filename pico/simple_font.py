def get_char(char):
    return FONT.get(char, FONT.get(' '))

def draw_char(epd, char, x, y, size=1):
    bitmap = get_char(char)
    for row in range(len(bitmap)):
        byte_val = bitmap[row]
        for col in range(8):
            if byte_val & (1 << (7 - col)):
                for sx in range(size):
                    for sy in range(size):
                        epd.set_pixel(x + col * size + sx, y + row * size + sy, 1)

def draw_text(epd, text, x, y, size=1, width=240):
    DISPLAY_WIDTH = 240
    MAX_CHAR_WIDTH = 5.45

    char_x = x
    current_y = y
    current_size = size
    line_count = 0
    i = 0

    while i < len(text):
        if text[i:i+1] == '[' and 'SIZE:' in text[i:i+10]:
            end = text.find(']', i)
            if end != -1:
                try:
                    size_str = text[i+1:end].split(':')[1]
                    new_size = int(size_str)
                    current_size = new_size
                    i = end + 1
                    chars_per_line = int(width / (MAX_CHAR_WIDTH * current_size))
                    continue
                except (ValueError, IndexError):
                    pass

        char = text[i]
        if char == '\n':
            current_y += 10 * current_size
            char_x = x
            line_count = 0
        else:
            draw_char(epd, char, char_x, current_y, current_size)
            char_x += 6 * current_size
            line_count += 1
            chars_per_line = int(width / (MAX_CHAR_WIDTH * current_size))

            if line_count >= chars_per_line:
                current_y += 10 * current_size
                char_x = x
                line_count = 0

        i += 1
